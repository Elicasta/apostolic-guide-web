export const EPISODE_10_SCRIPT = `# Cold Open
Acts does not treat the name used in baptism as decorative.

Peter says:

> be baptized every one of you in the name of Jesus Christ.

The Samaritans are baptized:

> in the name of the Lord Jesus.

The Ephesians are baptized:

> in the name of the Lord Jesus.

And Ananias tells Paul:

> arise, and be baptized, and wash away thy sins, calling on the name of the Lord.

That is the record.

So the question is not whether the apostles cared about the name.

They clearly did.

The question is:

**Why?**
@ref Acts 2:38; Acts 8:16; Acts 19:5; Acts 22:16
@note Begin with the repeated apostolic pattern before answering objections about wording.

---

# The Name Carries Authority And Identity
In Scripture, acting "in the name" means acting under the authority and identity of the one named.

Colossians says:

> whatsoever ye do in word or deed, do all in the name of the Lord Jesus.

The apostles preach in Jesus' name.

Heal in Jesus' name.

Cast out devils in Jesus' name.

Preach remission of sins in Jesus' name.

And baptize in Jesus' name.

This is not magic syllables.

The name identifies the authority and the Person into whom the believer is being baptized.
@ref Colossians 3:17; Luke 24:47; Acts 3:6; Acts 8:16
@note Define "in the name" positively as authority and identification.

---

# Baptism Is Into Jesus Christ
Romans 6 says:

> so many of us as were baptized into Jesus Christ were baptized into his death.

Galatians says:

> as many of you as have been baptized into Christ have put on Christ.

Colossians says we are:

> buried with him in baptism.

Baptism is not floating beside the gospel as an unrelated ceremony.

It is tied directly to Jesus Christ.

His death.

His burial.

His resurrection.

His name.

The apostolic baptismal name tells us whose saving work we are entering by faith.
@ref Romans 6:3-4; Galatians 3:27; Colossians 2:12
@note Keep baptism Christ-centered and connected to faith.

---

# Calling On The Name
Acts 22 makes the connection explicit.

Ananias tells Paul:

> arise, and be baptized, and wash away thy sins, calling on the name of the Lord.

There is baptism.

There is the name.

And there is the appeal to the Lord together in one command.

Peter had already preached:

> Repent, and be baptized every one of you in the name of Jesus Christ for the remission of sins.

Then Acts 4 says:

> there is none other name under heaven given among men, whereby we must be saved.

Scripture itself connects the saving work of Christ with His revealed name.

We should let that connection stand as strongly as the text states it.
@ref Acts 22:16; Acts 2:38; Acts 4:12
@note Let the texts carry the force without turning the name into an incantation.

---

# More Light Leads To Obedience
Acts 19 gives us a useful pattern.

Paul meets disciples who had already received John's baptism.

Their previous response was sincere.

But Paul teaches them more fully about Jesus Christ.

Then Scripture says:

> they were baptized in the name of the Lord Jesus.

Notice the response.

They do not argue that sincerity makes further obedience unnecessary.

They receive the truth they now understand and act on it.

More light leads to more obedience.

That is not contempt for what came before.

It is submission to what Scripture has now made clear.
@ref Acts 19:1-5
@note Keep this pastoral without weakening the call to obedience.

---

# Grace Produces Obedient Faith
Now establish the order correctly.

We are saved by grace.

We do not purchase salvation from God by performing religious acts.

But grace does not make obedience the enemy of faith.

When Jesus says repent, repentance is a response of faith.

When the gospel says be baptized, baptism is a response of faith.

When Scripture says call on His name, calling is a response of faith.

The power is not in our performance.

The power is in Jesus Christ and His death, burial, resurrection, Spirit, and name.

Grace gives the promise.

Faith receives the Word.

Faith obeys the gospel.
@ref Ephesians 2:8-10; Acts 2:38; Romans 6:3-4
@note Do not frame this as defending against "works salvation." Establish grace and obedience from Scripture.

---

# The Name Reveals Who Saves
Matthew says:

> thou shalt call his name JESUS: for he shall save his people from their sins.

Acts says:

> neither is there salvation in any other.

Philippians says every knee will bow at the name of Jesus.

The name matters because the One named matters.

Baptism in Jesus' name is not Apostolic branding.

It is identification with the Savior Scripture names.

The apostles did not separate baptism from the identity of Jesus Christ.

Neither should the text be separated now.
@ref Matthew 1:21; Acts 4:12; Philippians 2:9-11
@note Keep the focus on who Jesus is, not on denominational distinctiveness.

---

# Outro
Does the name used in baptism matter?

The New Testament record says yes.

The apostles repeatedly baptize in the name of Jesus Christ.

Baptism identifies us with Christ's death and burial.

Acts connects baptism with calling on the name of the Lord.

And salvation is proclaimed in the name of Jesus.

Not because a sound is magical.

Because Jesus Christ is the Savior into whom we are baptized.

But baptism is not the whole gospel response.

Peter also says:

> Repent... and ye shall receive the gift of the Holy Ghost.

So now we ask the larger question:

**What does Jesus mean when He says we must be born again?**
@ref Acts 2:38; John 3:3-5
@note End by widening from baptism to the full new-birth pattern.`;
